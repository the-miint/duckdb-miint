"""Update marked docs/ sections and the C++ manual entries from src/reference/.

Mark the .manual description, SQL fences, and website URL with the
manual:description, manual:example, and manual:url comments. Fragments
without these comments are published to the website only.
"""

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/reference"
HEADER = ROOT / "src/include/miint_function_reference.hpp"
DOCUMENTATION_ROOT = "https://the-miint.github.io/duckdb-miint"
SECTION = re.compile(
    r"^(<!-- BEGIN REFERENCE: ([a-z_][a-z0-9_]*) -->\n).*?(^<!-- END REFERENCE: \2 -->$)",
    re.MULTILINE | re.DOTALL,
)
SECTION_MARKER = re.compile(r"^<!-- (?:BEGIN|END) REFERENCE:", re.MULTILINE)
DESCRIPTION = re.compile(r"^<!-- manual:description -->\n([^\n]+)$", re.MULTILINE)
EXAMPLE = re.compile(
    r"^<!-- manual:example -->\n```sql[ \t]*\n((?:(?!^```)[^\n]*\n)+)^```+[ \t]*$",
    re.MULTILINE,
)
URL = re.compile(r"^<!-- manual:url (/(?!/)[^\s?#]+/#[^\s?#]+) -->$", re.MULTILINE)
MANUAL_MARKER = re.compile(r"^<!-- manual:.* -->\n", re.MULTILINE)


def render_manual(name, fragment):
    descriptions = DESCRIPTION.findall(fragment)
    examples = [example.removesuffix("\n") for example in EXAMPLE.findall(fragment)]
    urls = URL.findall(fragment)
    if not MANUAL_MARKER.search(fragment):
        return ""
    if (
        len(descriptions) != 1
        or not examples
        or len(urls) != 1
        or len(MANUAL_MARKER.findall(fragment)) != 2 + len(examples)
    ):
        raise ValueError(
            f"{name}: use one description line, at least one marked SQL fence, and one site-relative section URL"
        )

    description = f"{descriptions[0]} Full documentation: "
    quoted_examples = ",\n".join(
        f"\t    {json.dumps(example, ensure_ascii=False)}" for example in examples
    )
    return (
        f"inline duckdb::FunctionDescription {name}() {{\n"
        f"\tduckdb::FunctionDescription doc;\n"
        f"\tdoc.description = {json.dumps(description, ensure_ascii=False)};\n"
        f"\tdoc.description += documentation_root;\n"
        f"\tdoc.description += {json.dumps(urls[0], ensure_ascii=False)};\n"
        f"\tdoc.examples = {{\n{quoted_examples}\n\t}};\n"
        f"\treturn doc;\n"
        f"}}\n\n"
    )


def render_outputs():
    fragments = {
        path.stem: path.read_text(encoding="utf-8")
        for path in sorted(SOURCE.glob("*.md"))
    }
    remaining = set(fragments)
    outputs = {}

    def replace_section(match):
        name = match[2]
        if name not in remaining:
            raise ValueError(f"unknown or duplicate reference section: {name}")
        remaining.remove(name)
        return match[1] + MANUAL_MARKER.sub("", fragments[name]) + match[3]

    for page in sorted((ROOT / "docs").rglob("*.md")):
        original = page.read_text(encoding="utf-8")
        updated, count = SECTION.subn(replace_section, original)
        if len(SECTION_MARKER.findall(original)) != 2 * count:
            raise ValueError(
                f"{page.relative_to(ROOT)}: mismatched reference section markers"
            )
        if count:
            outputs[page] = updated

    if remaining:
        raise ValueError(
            f"missing reference section markers for: {', '.join(sorted(remaining))}"
        )

    entries = "".join(
        render_manual(name, fragment) for name, fragment in fragments.items()
    )
    outputs[HEADER] = (
        "// Generated by scripts/generate-reference.py from src/reference/.\n"
        "#pragma once\n\n"
        '#include "duckdb/parser/parsed_data/create_function_info.hpp"\n\n'
        "namespace miint::reference {\n\n"
        "// clang-format off\n"
        f"inline constexpr char documentation_root[] = {json.dumps(DOCUMENTATION_ROOT)};\n\n"
        f"{entries}"
        "// clang-format on\n"
        "} // namespace miint::reference\n"
    )
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if generated files need to be refreshed",
    )
    args = parser.parse_args()
    try:
        outputs = render_outputs()
    except ValueError as error:
        parser.exit(1, f"{error}\n")

    stale = [
        path
        for path, contents in outputs.items()
        if not path.exists() or path.read_text(encoding="utf-8") != contents
    ]
    if args.check and stale:
        paths = ", ".join(str(path.relative_to(ROOT)) for path in stale)
        parser.exit(
            1, f"Regenerate with scripts/generate-reference.py. Stale files: {paths}\n"
        )
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")


if __name__ == "__main__":
    main()
